import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,writeFile,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {createServer} from 'node:http';
import {once} from 'node:events';
import Fastify from 'fastify';
import {notionPairWriter,registerNotionNow} from '../dist/notion-now.js';

test('public /now coalesces refreshes, pins one private Notion page and never echoes snapshots', async t => {
  const dir=await mkdtemp('/tmp/hibi-now-test-');
  const id='01234567-89ab-cdef-0123-456789abcdef';
  const notionUrl='https://app.notion.com/p/'+id.replaceAll('-','');
  const token='test-bridge-credential'.repeat(3);
  await writeFile(join(dir,'notion-now-page.id'),id);
  await writeFile(join(dir,'notion-now-bridge.token'),token);
  let now=Date.parse('2026-11-23T10:00:00Z'), calls=0, respond, data;
  const app=Fastify();
  t.after(async()=>{await app.close();await rm(dir,{recursive:true,force:true});});
  const socketPath=join(dir,'refresh.sock');
  const bridge=createServer(async(req,res)=>{
    assert.equal(req.url,'/refresh');assert.equal(req.method,'POST');
    assert.equal(req.headers.authorization,'Bearer '+token);
    calls++;
    if (calls===1) await new Promise(resolve=>{respond=resolve;});
    res.writeHead(200,{'Content-Type':'application/json'});
    res.end(JSON.stringify(data ?? {pageId:id,checkedAt:new Date(now).toISOString()}));
  });
  bridge.listen(socketPath);
  await once(bridge,'listening');
  t.after(()=>new Promise(resolve=>bridge.close(resolve)));
  registerNotionNow(app,dir,socketPath,()=>now);
  const read=(accept='application/json',url='/now')=>app.inject({url,headers:{accept}});
  const json=read().then(r=>r.json()), html=read('text/html').then(r=>r);
  while (!respond) await new Promise(resolve=>setImmediate(resolve));
  respond();
  const [receipt,redirect]=await Promise.all([json,html]);
  assert.equal(calls,1);assert.equal(redirect.statusCode,302);assert.equal(redirect.headers.location,notionUrl);
  assert.deepEqual(receipt,{notionUrl,readWithNotion:true,checkedAt:'2026-11-23T10:00:00.000Z'});
  now+=44000;
  assert.equal((await read('*/*')).statusCode,302);assert.equal(calls,1);
  assert.equal((await read('application/json','/now?redirect=https://example.com')).statusCode,400);
  now+=1001;
  data={pageId:id,checkedAt:new Date(now).toISOString(),secret:'private patient data'};
  const failure=await read();
  assert.equal(failure.statusCode,503);assert.equal(failure.json().checkedAt,null);
  assert.equal(failure.json().notionUrl,notionUrl);assert.ok(!failure.body.includes(data.secret));
  assert.equal(calls,2);
  const stale=await read('text/html');
  assert.equal(stale.statusCode,503);assert.equal(stale.headers.location,undefined);
  assert.ok(stale.body.includes(notionUrl));assert.equal(calls,2);
  now+=5100;
  data={pageId:'f'.repeat(32),checkedAt:new Date(now).toISOString()};
  const wrongPage=await read();
  assert.equal(wrongPage.statusCode,503);assert.ok(!wrongPage.body.includes('f'.repeat(32)));
  now+=5100;
  data={pageId:id,checkedAt:'2026-11-23T08:59:00.000Z'};
  assert.equal((await read()).statusCode,503);
  now+=5100;data=null;
  assert.equal((await read()).statusCode,200);
});

test('internal Unix writer posts only the confirmation and accepts only the pinned page', async t => {
  const dir=await mkdtemp('/tmp/hibi-pair-test-');
  const id='2'.repeat(32), token='t'.repeat(32), proof='p'.repeat(43);
  await writeFile(join(dir,'notion-now-page.id'),id);
  await writeFile(join(dir,'notion-now-bridge.token'),token);
  let receipt={pageId:id};
  const socketPath=join(dir,'pair.sock');
  const server=createServer(async (req,res)=>{
    assert.equal(req.url,'/console-pair');assert.equal(req.method,'POST');
    assert.equal(req.headers.authorization,'Bearer '+token);
    const chunks=[];
    for await (const chunk of req) chunks.push(chunk);
    assert.deepEqual(JSON.parse(Buffer.concat(chunks).toString()),{proof});
    res.writeHead(200,{'Content-Type':'application/json'});res.end(JSON.stringify(receipt));
  });
  server.listen(socketPath);await once(server,'listening');
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));await rm(dir,{recursive:true,force:true});});
  const writer=notionPairWriter(dir,socketPath);
  assert.equal(await writer(proof),'https://app.notion.com/p/'+id);
  receipt={pageId:'f'.repeat(32)};await assert.rejects(()=>writer(proof));
  receipt={pageId:id,secret:'leak'};await assert.rejects(()=>writer(proof));
});
