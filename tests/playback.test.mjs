import test from 'node:test';
import assert from 'node:assert/strict';
import Fastify from 'fastify';
import { DatabaseSync } from 'node:sqlite';
import { runMigrations } from '../dist/db/migrations.js';
import { Repository } from '../dist/db/repo.js';
import { registerRoutes } from '../dist/routes.js';
import { DeviceAuth } from '../dist/device-auth.js';

test('playback retries, privacy boundaries and separate foreground state', async (t) => {
  const db = new DatabaseSync(':memory:');
  runMigrations(db);
  const app = Fastify();
  t.after(async () => { await app.close(); db.close(); });
  const devices = ['alpha', 'beta'].map(deviceId => ({token: `test-${deviceId}`, deviceId, deviceName: deviceId, platform: 'macos'}));
  registerRoutes(app, {repo: new Repository(db, 120), auth: new DeviceAuth(devices), labels: {name: x => x, liveDescription: () => ''}, rawLabels: {}, retentionDays: 0});
  const route = '/api/devices/playback';
  const post = (device, payload) => app.inject({method: 'POST', url: route, headers: device ? {authorization: `Bearer test-${device}`} : {}, payload});
  const get = (device, query = '') => app.inject({url: route + query, headers: device ? {authorization: `Bearer test-${device}`} : {}});
  const event = {player: 'com.apple.Music', state: 'playing', track: 'Private track', artist: 'Private artist', occurredAt: '2026-11-23T00:00:00.123Z'};
  assert.equal((await post(null, event)).statusCode, 401);
  assert.equal((await get(null)).statusCode, 401);
  assert.equal((await post('alpha', {...event, player:'com.unknown.app'})).statusCode, 400);
  assert.equal((await post('alpha', {...event, occurredAt:'not a time'})).statusCode, 400);
  assert.equal((await post('alpha', {...event, state:'unrecognized'})).statusCode, 400);
  assert.equal((await post('alpha', {...event, track:'x'.repeat(513)})).statusCode, 400);
  assert.equal((await post('alpha', {...event, deviceId:'beta'})).statusCode, 400);
  assert.equal((await post('alpha', event)).statusCode, 202);
  assert.equal((await post('alpha', {...event, player:'Apple Music', occurredAt:'2026-11-23T08:00:00.123+08:00', track:'conflicting retry'})).statusCode, 202);
  assert.equal((await post('beta', {...event, track:'Only beta'})).statusCode, 202);
  assert.equal((await post('alpha', {player:'com.spotify.client', state:'stopped', occurredAt:event.occurredAt})).statusCode, 202);
  const own = await get('alpha');
  assert.equal(own.statusCode, 200);
  assert.match(own.headers['cache-control'], /no-store/);
  assert.deepEqual(own.json().records, [ {...event, player: 'Apple Music'}, {player:'Spotify', state:'stopped', track:null, artist:null, occurredAt:event.occurredAt} ]);
  assert.equal((await get('alpha', '?deviceId=beta')).statusCode, 400);
  assert.equal((await get('beta')).json().records[0].track, 'Only beta');
  assert.equal((await get('alpha', '?limit=1')).json().records.length, 1);
  assert.deepEqual((await app.inject({url:'/api/devices/current'})).json().devices, []);
  assert.deepEqual((await app.inject({url:'/api/devices/timeline-query?date=2026-11-23'})).json().activities, []);
  assert.equal((await app.inject({url:'/api/devices/activity-summary?date=2026-11-23'})).json().totalSeconds, 0);
});
